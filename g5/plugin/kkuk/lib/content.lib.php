/** 컨텍스트 → 치환 변수 맵 */
function kkuk_content_vars(array $c) {
    $seed = $c['seed'] ?? '';
    $g = function ($k, $i, $fb = '') use ($c) {
        $a = $c[$k] ?? [];
        return $a[$i] ?? ($a ? $a[count($a) - 1] : $fb);
    };
    $v = [
        'SIDO'   => $c['sido']   ?? '',
        'GU'     => $c['gu']     ?? '',
        'CITY'   => $c['city']   ?? '',
        'DONG'   => $c['dong']   ?? '',
        'AREA'   => $c['area']   ?? '',
        'KINDL'  => kkuk_kind_label($c['kind'] ?? 'mixed'),
        'TRAIT'  => kkuk_trait_phrase($c['trait'] ?? 'mixed', $seed),
        'BLURB'  => rtrim((string)($c['blurb'] ?? ''), '.'),
        'NSHOP'  => (string)($c['nshop'] ?? 0),
        'NDONG'  => (string)($c['ndong'] ?? 0),
        'TEL_FMT'=> $c['tel_fmt'] ?? '',
    ];
    foreach ([1, 2, 3] as $i) {
        $v['ST' . $i]   = $g('stations', $i - 1);
        $v['MARK' . $i] = $g('marks',    $i - 1);
        $v['NEAR' . $i] = $g('near',     $i - 1);
        $v['LINE' . $i] = $g('lines',    $i - 1);
        $v['D' . $i]    = $g('dongs',    $i - 1);
        $v['A' . $i]    = $g('anchors',  $i - 1);
    }
    $v['SIB1'] = $g('siblings', 0);
    $v['SIB2'] = $g('siblings', 1);

    /* 경계 데이터에서 계산한 값 (앵커가 없는 동의 본문 재료) */
    $v['DIR'] = $c['dir'] ?? '';
    $v['KM2'] = isset($c['km2']) ? rtrim(rtrim(number_format((float)$c['km2'], 1), '0'), '.') : '';
    $v['GRADE_L'] = ['dense' => '조밀한', 'mid' => '보통 크기의',
                     'wide' => '넓은', 'vast' => '아주 넓은'][$c['grade'] ?? ''] ?? '';
    $nb = array_values($c['neighbors'] ?? []);
    foreach ([1, 2, 3, 4] as $i) $v['NB' . $i] = $nb[$i - 1] ?? ($nb ? $nb[count($nb) - 1] : '');
    $v['NBLIST'] = implode(' · ', array_slice($nb, 0, 3));
    foreach (['care','shop','pick','check','demand','time','price','guide','first','visit','area','tired','relax'] as $k) {
        $v['S_' . strtoupper($k)] = kkuk_syn($k, $seed, $k);
    }
    return $v;
}

/** 블록 배열의 순수 텍스트 길이 */
function kkuk_content_len(array $blocks) {
    $t = '';
    foreach ($blocks as $b) { $t .= $b['h']; foreach ($b['ps'] as $p) $t .= $p; }
    return mb_strlen(preg_replace('/\s+/u', '', $t), 'UTF-8');
}

/**
 * 본문 생성
 * @param array  $c    컨텍스트
 * @param string $kind 'gu' | 'dong'
 * @param int    $min  최소 글자 수(공백 제외)
 */
function kkuk_build_content(array $c, $kind = 'gu', $min = 1500) {
    $seed = $c['seed'] ?? 'kkuk';
    $vars = kkuk_content_vars($c);

    /* 섹션 풀 선택
       - 수기 앵커가 있는 동 : 앵커 풀 + 경계 기반 풀 일부를 섞어 재료를 넓힌다
       - 앵커가 없는 동     : 경계 기반 풀만 쓴다(확인되지 않은 서술을 만들지 않기 위해)
       - 인접 행정동이 없는 동(도서 지역) : 인접 정보를 쓰는 섹션을 뺀다 */
    if ($kind === 'dong') {
        $geo = kkuk_pool_dong_geo();
        if (empty($c['neighbors'])) {
            // 인접 행정동을 쓰는 섹션은 전부 뺀다(도서·외곽 지역). x0 가 x1 을 대신한다.
            $geo = array_values(array_filter($geo,
                fn($s) => !in_array($s['id'], ['x1', 'x2', 'x4', 'x6', 'x8', 'x13'], true)));
        } else {
            $geo = array_values(array_filter($geo, fn($s) => $s['id'] !== 'x0'));
        }
        if (!empty($c['anchors'])) {
            usort($geo, fn($a, $b) => kkuk_hash($seed . '|gx|' . $a['id']) <=> kkuk_hash($seed . '|gx|' . $b['id']));
            $pool = array_merge(kkuk_pool_dong(), array_slice($geo, 0, 5));
        } else {
            $pool = $geo;
        }
    } else {
        $pool = kkuk_pool_gu();
    }

    // 섹션 순서를 해시로 섞는다 → 페이지마다 글의 전개가 달라진다
    $idx = range(0, count($pool) - 1);
    usort($idx, function ($a, $b) use ($seed, $pool) {
        return kkuk_hash($seed . '|ord|' . $pool[$a]['id']) <=> kkuk_hash($seed . '|ord|' . $pool[$b]['id']);
    });

    $blocks = [];
    foreach ($idx as $i) {
        $s  = $pool[$i];
        $id = $s['id'];
        $b  = ['id' => $id, 'h' => kkuk_render(kkuk_one($s['h'], $seed, 'h:' . $id), $vars), 'ps' => []];
        foreach ($s['p'] as $pi => $group) {
            $txt = kkuk_render(kkuk_one($group, $seed, 'p:' . $id . ':' . $pi), $vars);
            if (trim($txt) !== '') $b['ps'][] = $txt;
        }
        $blocks[] = $b;
        if (count($blocks) >= 5 && kkuk_content_len($blocks) >= $min) break;
    }
    return $blocks;
}

