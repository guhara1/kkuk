/** 마지막 글자에 종성이 있는지 (한글 음절 기준). 숫자·영문은 발음 기준 예외표 사용 */
function kkuk_has_jong($word) {
    $word = preg_replace('/[\s\(\)\[\]·,\.\-~]+$/u', '', (string)$word);
    if ($word === '') return false;
    $last = mb_substr($word, -1, 1, 'UTF-8');
    $code = mb_ord($last, 'UTF-8');
    if ($code >= 0xAC00 && $code <= 0xD7A3) {
        return (($code - 0xAC00) % 28) !== 0;
    }
    // 숫자 : 0,1,3,6,7,8 은 종성 있음(영/일/삼/육/칠/팔)
    if ($last >= '0' && $last <= '9') return in_array($last, ['0','1','3','6','7','8'], true);
    // 영문 단독은 종성 없는 쪽으로 처리(실무상 '를/는' 선택이 자연스럽다)
    return false;
}

/** 종성이 'ㄹ'인지 — '으로/로' 판정에 필요 */
function kkuk_jong_rieul($word) {
    $last = mb_substr(preg_replace('/[\s\(\)\[\]·,\.\-~]+$/u', '', (string)$word), -1, 1, 'UTF-8');
    $code = mb_ord($last, 'UTF-8');
    if ($code >= 0xAC00 && $code <= 0xD7A3) return (($code - 0xAC00) % 28) === 8; // ㄹ
    return false;
}

/**
 * 조사만 반환. $type 은 '은는' '이가' '을를' '과와' '으로' '이나' '이라' '아야' 중 하나.
 */
function kkuk_josa($word, $type) {
    $j = kkuk_has_jong($word);
    switch ($type) {
        case '은는': case '는은': return $j ? '은' : '는';
        case '이가': case '가이': return $j ? '이' : '가';
        case '을를': case '를을': return $j ? '을' : '를';
        case '과와': case '와과': return $j ? '과' : '와';
        case '으로': case '로':   return (!$j || kkuk_jong_rieul($word)) ? '로' : '으로';
        case '이나': case '나이': return $j ? '이나' : '나';
        case '이라': case '라이': return $j ? '이라' : '라';
        case '이며':             return $j ? '이며' : '며';
        case '이다':             return $j ? '이다' : '다';
        case '이어서':           return $j ? '이어서' : '여서';
        case '아야': case '야아': return $j ? '아' : '야';
        default: return '';
    }
}

/**
 * {KEY} / {KEY:은는} 치환.
 * - {KEY:은는} → 값 + 알맞은 조사
 */
function kkuk_render($tpl, array $vars) {
    return preg_replace_callback('/\{([A-Z][A-Z0-9_]*)(?::([가-힣]+))?\}/u', function ($m) use ($vars) {
        $v = isset($vars[$m[1]]) ? (string)$vars[$m[1]] : '';
        if ($v === '') return '';
        if (!empty($m[2])) $v .= kkuk_josa($v, $m[2]);
        return $v;
    }, (string)$tpl);
}

