/** FAQ 5개 생성 (순서·문형 모두 지역별로 분기) */
function kkuk_faq(array $vars, $seed, $n = 5) {
    $pool = kkuk_faq_pool();
    $idx  = range(0, count($pool) - 1);
    usort($idx, function ($a, $b) use ($seed) {
        return kkuk_hash($seed . '|faq|' . $a) <=> kkuk_hash($seed . '|faq|' . $b);
    });
    $out = [];
    foreach (array_slice($idx, 0, $n) as $i) {
        $s = $pool[$i];
        $out[] = [
            'q' => kkuk_render(kkuk_one($s['q'], $seed, 'fq' . $i), $vars),
            'a' => kkuk_render(kkuk_one($s['a'], $seed, 'fa' . $i), $vars),
        ];
    }
    return $out;
}

